CREATE TABLE map_sectors (
    sector_number TINYINT UNSIGNED PRIMARY KEY,
    x_value DECIMAL(7, 5) UNSIGNED NOT NULL,
    y_value DECIMAL(7, 5) UNSIGNED NOT NULL,
    state VARCHAR(32) NOT NULL,
    CHECK (sector_number BETWEEN 1 AND 36),
    CHECK (x_value > 0 AND x_value <= 1),
    CHECK (y_value > 0 AND y_value <= 1),
    CHECK (state IN ('Healthy', 'Moderate', 'Dangerous'))
);

